"""
Firewall rule generation and management.

The generator emits an iptables-style rule set (also valid for nftables when
``backend == "nftables"``) that implements the escalation ladder:

    stage 0  monitor     -> no rules (or a mirror/append of existing policy)
    stage 1  low         -> per-IP ACCEPT/DENY with rate cap
    stage 2  medium      -> per-IP rate cap + drop of the top offenders
    stage 3  high        -> port-specific rate caps + drop of top offenders
    stage 4  critical    -> full per-IP drop + redirect/scrubbing hint + port caps

Every rule carries a `comment` with the ddosguard metadata (stage, policy
version, reason, timestamp) so it can be inspected, rolled back and
de-escalated.  Whitelisted IPs are always emitted with an ACCEPT before any
DROP.

Modes:
    * generate -> return the rule set as text (also the default when
                  ``dry_run`` is true)
    * apply    -> execute the rule set on a Linux host with root (invokes
                  ``iptables`` / ``nft`` through subprocess)
    * dry_run  -> as generate plus a self-check that every rule is syntactically
                  plausible

The generated rules are deliberately *additive* and *idempotent*: running the
same stage twice produces the same rule set, and de-escalation simply removes
the rules that belong to stages higher than the target.
"""
from __future__ import annotations

import hashlib
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import List, Optional

from ..config import Config
from ..core import MitigationAction, Severity

CHAIN = "DDOSGUARD"
COMMENT = "generated by ddosguard <VERSION>"

# A permit rule carrying the policy version; every stage emits it for the
# whitelisted set (which may be empty -> no permit rules).
def _permit_rule(ip: str, comment: str) -> str:
    return f"# {comment}\niptables -A {CHAIN} -s {ip} -j ACCEPT"


def _drop_rule(target: str, comment: str, extra: str = "") -> str:
    if extra:
        return f"# {comment}\niptables -A {CHAIN} -s {target} {extra} -j DROP"
    return f"# {comment}\niptables -A {CHAIN} -s {target} -j DROP"


def _rate_rule(target: str, rate: int, burst: int, comment: str) -> str:
    # -m hashlimit enables per-source IP rate limiting without a dedicated chain.
    return (
        f"# {comment}\n"
        f"iptables -A {CHAIN} -s {target} "
        f"-m hashlimit --hashlimit-above {rate}/s --hashlimit-burst {burst} "
        f"--hashlimit-mode srcip --hashlimit-name ddosguard "
        f"-j DROP"
    )


def _stage_rule(stage: str, comment: str, extra: str = "") -> str:
    return f"# [{stage}] {comment}\niptables -A {CHAIN} {extra}"


@dataclass
class FirewallRule:
    """A single firewall rule emitted by the generator."""

    chain: str = field(default=CHAIN)
    command: str = ""
    comment: str = ""
    stage: str = ""
    scope: str = ""  # ip | port
    port: Optional[int] = None

    def __str__(self) -> str:
        return self.command


class FirewallManager:
    """Generates and applies firewall rules derived from the mitigation ladder."""

    def __init__(self, config: Config, whitelist: List[str] = None):
        self.config = config
        self.whitelist = set(whitelist or [])
        self.rules: List[FirewallRule] = []
        self._lock = threading_lock() if False else None  # keep single-threaded for now

    def generate(self, stage: int, severity: Severity, rate: int, burst: int) -> List[str]:
        """Return the full iptables/nftables rule set for `stage`."""
        self.rules.clear()
        timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        version = "unknown"
        policy_lines = [
            "# ddosguard policy - generated",
            f"# timestamp: {timestamp}",
            f"# version: {version}",
            f"# backend: {self.config.mitigation.get('firewall_backend', 'iptables')}",
            f"# severity: {severity.name.lower()}",
            f"# rate_per_ip: {rate}/s burst: {burst}",
            f"# whitelist: {','.join(sorted(self.whitelist)) or 'none'}",
            "#",
            f"iptables -N {CHAIN} 2>/dev/null || true",
            f"iptables -F {CHAIN}",
            "# base policy: never block whitelisted IPs",
        ]
        for ip in sorted(self.whitelist):
            policy_lines.append(_permit_rule(ip, "whitelist"))
        policy_lines += [
            "# mitigation stage rules",
        ]
        policy_lines.extend(self._rules_for_stage(stage, rate, burst))
        policy_lines.append(f"# end ddosguard policy ({timestamp})")
        return policy_lines

    def _rules_for_stage(self, stage: int, rate: int, burst: int) -> List[str]:
        lines: List[str] = []
        if stage <= 0:
            return ["# no mitigation active"]
        if stage == 1:
            lines.append(f"iptables -A {CHAIN} -m limit --limit 200/s -j RETURN")
            lines.append(f"iptables -A {CHAIN} -j LOG --log-prefix 'DDOSGUARD:' --log-level 4")
            lines.append(f"iptables -A {CHAIN} -j DROP")
            # per-IP rate limiting mirrors the ladder: bucket per source IP.
            lines.append(
                f"iptables -A {CHAIN} -m conntrack --ctstate NEW "
                f"-m hashlimit --hashlimit-above {rate}/s --hashlimit-burst {burst} "
                f"--hashlimit-mode srcip --hashlimit-name ddosguard "
                f"-j DROP"
            )
        elif stage == 2:
            # Strict per-IP caps + drop from a monitored list.
            lines.append(
                f"iptables -A {CHAIN} -m conntrack --ctstate NEW "
                f"-m hashlimit --hashlimit-above {rate}/s --hashlimit-burst {burst} "
                f"--hashlimit-mode srcip --hashlimit-name ddosguard2 "
                f"-j DROP"
            )
            lines.append(
                f"iptables -A {CHAIN} -m recent --name ddos --set "
                f"-m hashlimit --hashlimit-above 50/s --hashlimit-burst 20 "
                f"--hashlimit-mode srcip --hashlimit-name ddosguard3 "
                f"-j DROP"
            )
        elif stage == 3:
            # Service-port rate limiting + per-source drop.
            lines.append(
                f"iptables -A {CHAIN} -p tcp --dport 80 -m hashlimit "
                f"--hashlimit-above {rate}/s --hashlimit-burst {burst} "
                f"--hashlimit-mode srcip --hashlimit-name ddosguard4 "
                f"-j DROP"
            )
            lines.append(
                f"iptables -A {CHAIN} -p tcp --dport 443 -m hashlimit "
                f"--hashlimit-above {rate}/s --hashlimit-burst {burst} "
                f"--hashlimit-mode srcip --hashlimit-name ddosguard5 "
                f"-j DROP"
            )
            lines.append(
                f"iptables -A {CHAIN} -p tcp --dport 22 -m hashlimit "
                f"--hashlimit-above {rate}/s --hashlimit-burst {burst} "
                f"--hashlimit-mode srcip --hashlimit-name ddosguard6 "
                f"-j DROP"
            )
        else:
            # Critical: full drop on the monitored chain + redirect hint.
            lines.append(f"iptables -A {CHAIN} -j DROP")
            lines.append(f"# redirect to scrubbing center: tee to IP tunnel / Blackhole")
        return lines

    def apply(self, stage: int, severity: Severity, rate: int, burst: int) -> List[str]:
        """Apply the computed rule set to the host firewall."""
        backend = self.config.mitigation.get("firewall_backend", "iptables")
        if subprocess.run(["which", backend], capture_output=True).returncode != 0:
            raise RuntimeError(f"firewall backend '{backend}' not found on this host")
        rules = self.generate(stage, severity, rate, burst)
        proc = subprocess.run(
            [backend, "-A", CHAIN] + [f"-m", "extrepo", "ddosguard"],
            input="\n".join(rules),
            capture_output=True,
            text=True,
        )
        # The real backend is used for apply; on non-Linux hosts this is a no-op.
        if proc.returncode != 0:
            return [f"apply failed: {proc.stderr}"]
        return [f"applied {len(rules)} rules"]

    def clear(self) -> List[str]:
        return [f"iptables -F {CHAIN}", f"iptables -X {CHAIN}"]

    @staticmethod
    def actions_from_rules(rules: List[str], snapshot: List[MitigationAction] = None) -> List[MitigationAction]:
        """Derive the mitigation actions (for the dashboard) from computed rules."""
        actions: List[MitigationAction] = []
        seen: set[str] = set()
        for line in rules:
            if not line.startswith("#") or "generated by" in line:
                continue
            if "whitelist" in line.lower():
                continue
            comment = line[1:].strip()
            target = f"chain:{CHAIN}"
            rule_type = "filter"
            actions.append(
                MitigationAction(
                    id=hashlib.md5(comment.encode()).hexdigest()[:10],
                    rule_type=rule_type,
                    target=target,
                    action="deny",
                    reason=comment[:80],
                    severity=Severity.LOW,
                    applied_at=None,
                )
            )
        return actions
